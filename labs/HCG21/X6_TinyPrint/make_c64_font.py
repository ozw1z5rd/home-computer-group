def glyph(code):
    """Return the 8 row bytes for an ASCII code 32..127."""
    if 32 <= code <= 95:
        return GLYPHS[code]
    if 96 <= code <= 122:
        # lowercase -> uppercase (authentic C64 uppercase-mode behaviour)
        return GLYPHS[code - 32]
    if code == 123:
        return GLYPHS[91]  # { -> [
    if code == 124:
        return GLYPHS[92]  # | -> backslash
    if code == 125:
        return GLYPHS[93]  # } -> ]
    if code == 126:
        return GLYPHS[92]  # ~ -> backslash
    if code == 127:
        return GLYPHS[32]  # DEL -> space
    return GLYPHS[32]


def main():
    out = bytearray()
    for code in range(32, 128):
        out.extend(glyph(code))
    with open("c64.ch8", "wb") as fh:
        fh.write(out)
    print("wrote c64.ch8 (%d bytes)" % len(out))


if __name__ == "__main__":
    main()
